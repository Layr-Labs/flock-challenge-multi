// X9 read-only deep input: crown first-sweep arithmetic and 2048-row shape.
pub(crate) unsafe fn xseed_virtual_first(
    src: *const F128, dst: *mut F128, p: &PreparedFour, hint: u8,
) {
    let ordered = super::super::ntt_alias_load_order_enabled();
    unsafe {
        match (hint, ordered) {
            (0, false) => xseed_virtual_first_impl::<0, 0>(src, dst, p),
            (0, true) => xseed_virtual_first_impl::<0, 1>(src, dst, p),
            (1, false) => xseed_virtual_first_impl::<1, 0>(src, dst, p),
            (1, true) => xseed_virtual_first_impl::<1, 1>(src, dst, p),
            (_, false) => xseed_virtual_first_impl::<2, 0>(src, dst, p),
            (_, true) => xseed_virtual_first_impl::<2, 1>(src, dst, p),
        }
    }
}

unsafe fn xseed_virtual_first_impl<const H: u8, const ORD: u8>(
    src: *const F128, dst: *mut F128, p: &PreparedFour,
) {
    let lead = (p.prefetch_lines * 4).min(64);
    unsafe {
        for r in 0..128 {
            let lanes = if r & 1 != 0 { 60 } else { 64 };
            if r == 127 || H == 0 {
                butterfly_four_private_into::<128, 64, 64, 0, ORD>(
                    src.add(r * 64), dst.add(r * 64), p, lanes * 16, src,
                );
            } else {
                butterfly_four_private_into::<128, 64, 64, H, ORD>(
                    src.add(r * 64), dst.add(r * 64), p, lanes * 16,
                    src.add(r * 64 + lead),
                );
            }
            if r & 1 != 0 {
                for i in 0..16 {
                    core::ptr::write_bytes(dst.add((i * 128 + r) * 64 + 60), 0, 4);
                }
            }
        }
    }
}

