/// Keep just one child of a butterfly level; output must not alias the right
/// input half. Left-half in-place compaction is supported.
#[inline(never)]
#[target_feature(enable="avx512f,vpclmulqdq")]
pub(crate) unsafe fn xseed_virtual_project(src:*const F128, dst:*mut F128,
    half_fields:usize, t:F128, right:bool) {
    use core::arch::x86_64::*;
    debug_assert!(half_fields.is_multiple_of(4));
    unsafe {
        let tw=tw_x4::<false,true>(t);
        for i in (0..half_fields).step_by(4) {
            let a=_mm512_loadu_si512(src.add(i).cast());
            let b=_mm512_loadu_si512(src.add(half_fields+i).cast());
            let mut out=_mm512_xor_si512(a,mul_x4::<false,true>(tw,b));
            if right {out=_mm512_xor_si512(out,b);}
            _mm512_storeu_si512(dst.add(i).cast(),out);
        }
    }
}

/// Keep both children with one product per pair. Output is either disjoint
/// from input or exactly aliases it; partial overlap is unsupported. Each
/// input half contains `half_fields` initialized elements.
#[inline(never)]
#[target_feature(enable="avx512f,vpclmulqdq")]
pub(crate) unsafe fn xseed_virtual_project_pair(src:*const F128, dst:*mut F128,
    half_fields:usize, t:F128) {
    use core::arch::x86_64::*;
    debug_assert!(half_fields.is_multiple_of(4));
    unsafe {
        let tw=tw_x4::<false,true>(t);
        for i in (0..half_fields).step_by(4) {
            let a=_mm512_loadu_si512(src.add(i).cast());
            let b=_mm512_loadu_si512(src.add(half_fields+i).cast());
            let left=_mm512_xor_si512(a,mul_x4::<false,true>(tw,b));
            _mm512_storeu_si512(dst.add(i).cast(),left);
            _mm512_storeu_si512(dst.add(half_fields+i).cast(),_mm512_xor_si512(left,b));
        }
    }
}

/// Collapse three single-child levels with one shared field reduction.
/// `t` contains the three path twiddles, already XOR-adjusted for right children.
/// Input has eight initialized `eighth_fields` chunks. Output is disjoint or
/// exactly the left prefix; every lane's eight inputs precede its output store.
#[inline(never)]
#[target_feature(enable="avx512f,avx512bw,vpclmulqdq")]
pub(crate) unsafe fn xseed_virtual_project_three(src:*const F128,dst:*mut F128,
    eighth_fields:usize,t:[F128;3]) {
    use core::arch::x86_64::*;
    debug_assert!(eighth_fields.is_multiple_of(4));
    unsafe {
        let ab=t[0]*t[1];
        let c1=tw_x4::<false,true>(t[2]);
        let c2=tw_x4::<false,true>(t[1]);
        let c3=tw_x4::<false,true>(t[1]*t[2]);
        let c4=tw_x4::<false,true>(t[0]);
        let c5=tw_x4::<false,true>(t[0]*t[2]);
        let c6=tw_x4::<false,true>(ab);
        let c7=tw_x4::<false,true>(ab*t[2]);
        let poly=_mm512_set_epi64(0,0x87,0,0x87,0,0x87,0,0x87);
        for i in (0..eighth_fields).step_by(4) {
            let mut lo=_mm512_loadu_si512(src.add(i).cast());
            let mut hi=_mm512_setzero_si512();
            macro_rules! term {($n:literal,$c:ident)=>{{
                let v=_mm512_loadu_si512(src.add($n*eighth_fields+i).cast());
                lo=_mm512_xor_si512(lo,_mm512_xor_si512(
                    _mm512_clmulepi64_epi128::<0x00>(v,$c.0),
                    _mm512_clmulepi64_epi128::<0x01>(v,$c.1)));
                hi=_mm512_xor_si512(hi,_mm512_xor_si512(
                    _mm512_clmulepi64_epi128::<0x10>(v,$c.0),
                    _mm512_clmulepi64_epi128::<0x11>(v,$c.1)));
            }}}
            term!(1,c1);term!(2,c2);term!(3,c3);term!(4,c4);
            term!(5,c5);term!(6,c6);term!(7,c7);
            let out=_mm512_xor_si512(lo,_mm512_xor_si512(
                _mm512_bslli_epi128::<8>(hi),_mm512_clmulepi64_epi128::<0x01>(hi,poly)));
            _mm512_storeu_si512(dst.add(i).cast(),out);
        }
    }
}

