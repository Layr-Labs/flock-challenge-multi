#[cfg(all(test, target_feature = "avx512bw"))]
mod xseed_seed_pair_tests {
    use super::*;

    #[test]
    fn paired_windows_match_incumbent_with_guards() {
        let mut state = 0xd12e_47a2_9c81_4bbdu64;
        let mut next = || {
            state ^= state << 13; state ^= state >> 7; state ^= state << 17;
            F128::new(state, state.rotate_left(27) ^ 0x94d0_49bb_1331_11eb)
        };
        let guard = F128::new(0xa5a5_a5a5_a5a5_a5a5, 0x5a5a_5a5a_5a5a_5a5a);
        let mut cases = 0;
        for source_cols in [8usize, 16, 32, 64] {
            for active in (4..=source_cols).step_by(4) {
                for low in [false, true] {
                    for perm in [false, true] {
                        let step = if perm { 16 * 64 } else { 64 };
                        let offset = 5 + active % 4;
                        let mut input: Vec<F128> = (0..8*source_cols+8).map(|_|next()).collect();
                        if active == 4 { input.fill(F128::ZERO); }
                        if active == 8 { input.fill(F128::new(!0, !0)); }
                        let saved = input.clone();
                        let mut tw = [next(), next(), next(), next()];
                        if low { tw[1].hi = 0; }
                        let prepared = core::array::from_fn(|i| if i%2==0 { tw[i/2] }
                            else { tw[i/2] * F128::new(0, 1) });
                        let mut expected = vec![guard; 512 * 64 + 16];
                        let mut actual = expected.clone();
                        unsafe {
                            for bit in 0..2 {
                                let dst = expected.as_mut_ptr().add(offset+bit*step);
                                seed_window_prepared(input.as_ptr().add(1),2,bit,dst,
                                    dst.add(256*64),source_cols,active,&prepared);
                            }
                            let dst = actual.as_mut_ptr().add(offset);
                            xseed_seed_window_pair(input.as_ptr().add(1),dst,dst.add(step),
                                source_cols,active,&prepared);
                        }
                        assert_eq!(actual,expected,"cols={source_cols} active={active} low={low} perm={perm}");
                        assert_eq!(input,saved);
                        cases += 1;
                    }
                }
            }
        }
        assert_eq!(cases,120);
    }
}

/// Two disjoint kbit windows, with the incumbent eight-lane arithmetic.
/// The caller owns every input field and destination row until return.
#[cfg(target_feature = "avx512bw")]
#[inline]
pub(super) unsafe fn xseed_seed_window_pair(
    src: *const F128, dst: *mut F128, dst_next: *mut F128,
    source_cols: usize, active: usize, prepared: &[F128; 8],
) {
    unsafe {
        if prepared[2].hi == 0 {
            xseed_seed_pair_impl::<true>(src, dst, dst_next, source_cols, active, prepared);
        } else {
            xseed_seed_pair_impl::<false>(src, dst, dst_next, source_cols, active, prepared);
        }
    }
}
