//! Experimental two-plane p0-to-p5 rebalance for the selected-word root fold.
//! Default-off caller gate: FLOCK_XGLM_ROOT_LOOKUP. No protocol changes.
use core::arch::x86_64::*;

/// [stripe][plane 14 or 15][low or high nibble][64 repeated entries].
#[repr(C, align(64))]
pub(crate) struct RootLookupTables(pub [[[ [u8; 64]; 2]; 2]; 8]);

impl RootLookupTables {
    pub(crate) fn zero() -> Self { Self([[[[0; 64]; 2]; 2]; 8]) }
}

/// Build tables once per tile, amortized over all selected-word blocks.
/// Safety: caller ensures AVX512F/BW and GFNI.
#[target_feature(enable = "avx512f,avx512bw,gfni")]
pub(crate) unsafe fn build_root_lookup(mats: &[u64; 128], out: &mut RootLookupTables) {
    let low: [u8; 64] = core::array::from_fn(|i| (i & 15) as u8);
    let high: [u8; 64] = core::array::from_fn(|i| ((i & 15) << 4) as u8);
    unsafe {
        let lo = _mm512_loadu_si512(low.as_ptr().cast());
        let hi = _mm512_loadu_si512(high.as_ptr().cast());
        for stripe in 0..8 {
            for plane in 0..2 {
                let matrix = _mm512_set1_epi64(mats[stripe * 16 + 14 + plane] as i64);
                _mm512_storeu_si512(out.0[stripe][plane][0].as_mut_ptr().cast(),
                    _mm512_gf2p8affine_epi64_epi8::<0>(lo, matrix));
                _mm512_storeu_si512(out.0[stripe][plane][1].as_mut_ptr().cast(),
                    _mm512_gf2p8affine_epi64_epi8::<0>(hi, matrix));
            }
        }
    }
}

// Public rival 0194c7d2: request write ownership for the next private bank.
// Default off here; the scorer decides whether the unseparated rival signal transfers.
fn xglm_prefetchw_enabled() -> bool {
    static ON: std::sync::LazyLock<bool> =
        std::sync::LazyLock::new(|| std::env::var_os("FLOCK_XGLM_PREFETCHW").is_some());
    *ON
}

